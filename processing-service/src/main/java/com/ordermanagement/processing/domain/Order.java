package com.ordermanagement.processing.domain;

import com.ordermanagement.processing.exception.InvalidStatusTransitionException;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.Version;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import org.springframework.data.mongodb.core.mapping.Field;
import org.springframework.data.mongodb.core.mapping.FieldType;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;

@Document(collection = "orders")
@CompoundIndex(name = "status_createdAt", def = "{ 'status': 1, 'createdAt': -1 }")
public class Order {

    /** Same id generated by the order-service, which makes redelivered messages easy to detect. */
    @Id
    private String id;
    private String customerName;
    private String customerEmail;
    private List<OrderItem> items;
    @Field(targetType = FieldType.DECIMAL128)
    private BigDecimal totalAmount;
    private OrderStatus status;
    @Indexed
    private Instant createdAt;
    private Instant updatedAt;
    /** Optimistic locking: two concurrent status updates cannot silently overwrite each other. */
    @Version
    private Long version;

    /** Used by Spring Data when reading documents. */
    protected Order() {
    }

    public Order(String id, String customerName, String customerEmail, List<OrderItem> items,
                 BigDecimal totalAmount, Instant createdAt) {
        this.id = id;
        this.customerName = customerName;
        this.customerEmail = customerEmail;
        this.items = List.copyOf(items);
        this.totalAmount = totalAmount;
        this.status = OrderStatus.CREATED;
        this.createdAt = createdAt;
        this.updatedAt = createdAt;
    }

    /**
     * Moves the order to a new status, following the lifecycle defined in {@link OrderStatus}.
     *
     * @throws InvalidStatusTransitionException when the lifecycle does not allow the change
     */
    public void changeStatus(OrderStatus newStatus, Instant changedAt) {
        if (!status.canTransitionTo(newStatus)) {
            throw new InvalidStatusTransitionException(id, status, newStatus);
        }
        this.status = newStatus;
        this.updatedAt = changedAt;
    }

    public String getId() {
        return id;
    }

    public String getCustomerName() {
        return customerName;
    }

    public String getCustomerEmail() {
        return customerEmail;
    }

    public List<OrderItem> getItems() {
        return items;
    }

    public BigDecimal getTotalAmount() {
        return totalAmount;
    }

    public OrderStatus getStatus() {
        return status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public Long getVersion() {
        return version;
    }
}
